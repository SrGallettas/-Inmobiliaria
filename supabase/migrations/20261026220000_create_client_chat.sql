create table if not exists public.conversations (
  id bigint generated by default as identity primary key,
  property_id bigint not null references public.properties(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'open' check (status in ('open', 'closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (property_id, user_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(trim(content)) between 1 and 2000),
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists messages_conversation_created_idx
on public.messages (conversation_id, created_at);

alter table public.conversations enable row level security;
alter table public.messages enable row level security;

revoke all on table public.conversations, public.messages from anon, authenticated;
grant select, insert on table public.conversations, public.messages to authenticated;
grant usage, select on sequence public.conversations_id_seq, public.messages_id_seq to authenticated;

create policy "Los clientes consultan sus conversaciones"
on public.conversations for select to authenticated
using (user_id = (select auth.uid()));

create policy "Los clientes crean sus conversaciones"
on public.conversations for insert to authenticated
with check (user_id = (select auth.uid()));

create policy "Los clientes consultan sus mensajes"
on public.messages for select to authenticated
using (exists (
  select 1 from public.conversations
  where conversations.id = messages.conversation_id
    and conversations.user_id = (select auth.uid())
));

create policy "Los clientes envían sus mensajes"
on public.messages for insert to authenticated
with check (
  sender_id = (select auth.uid())
  and exists (
    select 1 from public.conversations
    where conversations.id = messages.conversation_id
      and conversations.user_id = (select auth.uid())
      and conversations.status = 'open'
  )
);

create or replace function public.touch_conversation_on_message()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  update public.conversations set updated_at = now() where id = new.conversation_id;
  return new;
end;
$$;

drop trigger if exists on_message_created on public.messages;
create trigger on_message_created
  after insert on public.messages
  for each row execute procedure public.touch_conversation_on_message();
