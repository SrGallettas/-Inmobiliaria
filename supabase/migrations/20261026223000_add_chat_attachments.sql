create table if not exists public.message_attachments (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.messages(id) on delete cascade,
  uploader_id uuid not null references public.profiles(id) on delete cascade,
  storage_path text not null unique,
  media_type text not null check (media_type in ('image', 'video')),
  mime_type text not null,
  original_name text not null,
  size_bytes bigint not null check (size_bytes > 0 and size_bytes <= 52428800),
  created_at timestamptz not null default now()
);

alter table public.message_attachments enable row level security;
revoke all on table public.message_attachments from anon, authenticated;
grant select, insert on table public.message_attachments to authenticated;
grant usage, select on sequence public.message_attachments_id_seq to authenticated;

create policy "Los clientes consultan adjuntos de sus conversaciones"
on public.message_attachments for select to authenticated
using (exists (
  select 1 from public.messages
  join public.conversations on conversations.id = messages.conversation_id
  where messages.id = message_attachments.message_id
    and conversations.user_id = (select auth.uid())
));

create policy "Los clientes adjuntan archivos a sus mensajes"
on public.message_attachments for insert to authenticated
with check (
  uploader_id = (select auth.uid())
  and exists (
    select 1 from public.messages
    join public.conversations on conversations.id = messages.conversation_id
    where messages.id = message_attachments.message_id
      and messages.sender_id = (select auth.uid())
      and conversations.user_id = (select auth.uid())
  )
);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'chat-media',
  'chat-media',
  false,
  52428800,
  array['image/jpeg', 'image/png', 'image/webp', 'video/mp4', 'video/webm', 'video/quicktime']
)
on conflict (id) do update set
  public = false,
  file_size_limit = 52428800,
  allowed_mime_types = excluded.allowed_mime_types;

create policy "Los clientes suben archivos de chat"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'chat-media'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
);

create policy "Los clientes consultan sus archivos de chat"
on storage.objects for select to authenticated
using (
  bucket_id = 'chat-media'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
);

create policy "Los clientes eliminan sus archivos de chat"
on storage.objects for delete to authenticated
using (
  bucket_id = 'chat-media'
  and owner_id = (select auth.uid()::text)
);
