create table if not exists public.properties (
  id bigint generated by default as identity primary key,
  title text not null,
  location text not null,
  city text not null,
  price integer not null check (price > 0),
  bedrooms smallint not null check (bedrooms >= 0),
  bathrooms smallint not null check (bathrooms >= 0),
  area integer not null check (area > 0),
  type text not null,
  operation text not null check (operation in ('comprar', 'alquilar')),
  badge text,
  featured boolean not null default false,
  date_added date not null default current_date,
  image text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.properties enable row level security;

revoke all on table public.properties from anon, authenticated;
grant select on table public.properties to anon, authenticated;

create policy "Las propiedades publicadas son visibles para todos"
on public.properties
for select
to anon, authenticated
using (true);

