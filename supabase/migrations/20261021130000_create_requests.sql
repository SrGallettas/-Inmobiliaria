create table if not exists public.contact_requests (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 120),
  email text not null check (char_length(email) <= 254),
  reason text not null check (reason in ('Quiero comprar', 'Quiero vender', 'Solicitar una visita')),
  message text not null check (char_length(message) between 10 and 3000),
  status text not null default 'new' check (status in ('new', 'in_progress', 'closed')),
  created_at timestamptz not null default now()
);

create table if not exists public.visit_requests (
  id bigint generated by default as identity primary key,
  property_id bigint references public.properties(id) on delete set null,
  property_title text not null,
  name text not null check (char_length(name) between 2 and 120),
  email text not null check (char_length(email) <= 254),
  phone text not null check (char_length(phone) between 9 and 30),
  preferred_date date not null check (preferred_date >= current_date),
  message text check (char_length(message) <= 3000),
  status text not null default 'new' check (status in ('new', 'in_progress', 'closed')),
  created_at timestamptz not null default now()
);

alter table public.contact_requests enable row level security;
alter table public.visit_requests enable row level security;

revoke all on table public.contact_requests, public.visit_requests from anon, authenticated;
grant insert on table public.contact_requests, public.visit_requests to anon, authenticated;
grant usage, select on sequence public.contact_requests_id_seq, public.visit_requests_id_seq to anon, authenticated;

create policy "Cualquiera puede enviar una solicitud de contacto"
on public.contact_requests for insert to anon, authenticated with check (true);

create policy "Cualquiera puede solicitar una visita"
on public.visit_requests for insert to anon, authenticated with check (true);
